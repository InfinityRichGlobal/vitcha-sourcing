import { test, expect } from '@playwright/test';
import { capture } from './capture';
test.use({ viewport: { width: 390, height: 844 }, launchOptions: { args: ['--disable-gpu'] } });

test.beforeEach(async ({ page }) => { await page.route('https://tiles.openfreemap.org/**', r => r.fulfill({ status: 503, body: 'Non-map test' })); });

test('mobile history shows actor, time and counts without duplicate media or comment text', async ({ page }) => {
  const login = await page.request.post('/api/login', { data: { idOrEmail: 'qa-admin', pin: 'qa-only-876543' } });
  const { token } = await login.json(); const headers = { Authorization: `Bearer ${token}` };
  const id = 'qa-activity-' + Date.now();
  const photos = Array.from({ length: 5 }, (_, i) => `/uploads/history-${i}.jpg`);
  const create = await page.request.post('/api/suppliers', { headers, data: { id, name: 'ร้านประวัติย่อ', category: 'ชา', rating: 4, quickTags: [], photos: { storefrontAndAtmosphere: photos, contactCards: [] }, catalogItems: [], location: { lat: 13.7, lng: 100.5 } } });
  expect(create.ok()).toBeTruthy(); const record = (await create.json()).item;
  const comment = await page.request.post(`/api/suppliers/${id}/actions`, { headers, data: { action: 'comment', operationId: id + '-comment', data: { text: 'ข้อความจริงอยู่ในความคิดเห็นเท่านั้น', media: photos.map((url, i) => ({ id: String(i), type: 'image', url })), photoUrl: photos[0], voiceUrl: '/audio/sample-feedback-1.m4a' } } });
  expect(comment.ok()).toBeTruthy();
  expect((await page.request.post('/api/suppliers', { headers, data: { ...record, revision: 2, photos: { storefrontAndAtmosphere: photos.slice(3), contactCards: [] } } })).ok()).toBeTruthy();
  await page.addInitScript(t => sessionStorage.setItem('vitcha_session_token', t), token);
  await page.goto(`/?view=${id}&type=supplier`, { waitUntil: 'domcontentloaded' });
  const timeline = page.getByTestId('activity-timeline'); await expect(timeline).toBeVisible(); await timeline.scrollIntoViewIfNeeded();
  await expect(timeline.getByTestId('activity-event')).toHaveCount(3);
  await expect(timeline.getByTestId('activity-event').first()).toContainText('ลบรูปภาพ 3 รูป');
  await expect(timeline).toContainText('เพิ่มรูปภาพ 5 รูป');
  await expect(timeline).toContainText('แสดงความคิดเห็น · แนบรูปภาพ 5 รูป · แนบเสียง 1 ไฟล์');
  await expect(timeline).not.toContainText('ข้อความจริงอยู่ในความคิดเห็นเท่านั้น');
  await expect(timeline.getByTestId('activity-avatar')).toHaveCount(3);
  await expect(timeline.getByTestId('activity-avatar').first()).toHaveAttribute('alt', 'โปรไฟล์ QA admin');
  await expect(timeline.locator('img:not([data-testid="activity-avatar"]), audio, video, details')).toHaveCount(0);
  expect(await timeline.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBeTruthy();
  await timeline.getByLabel('ประเภทประวัติ').selectOption('comments');
  await expect(timeline.getByTestId('activity-event')).toHaveCount(1);
  await expect(timeline.locator('time')).not.toBeEmpty();
  await expect(timeline.locator('strong')).toContainText('QA admin');
  await page.reload(); await expect(timeline.getByTestId('activity-event')).toHaveCount(3);
  await timeline.getByRole('button', { name: 'เรียงใหม่ก่อน' }).click();
  await expect(timeline.getByTestId('activity-event').first()).toContainText('สร้างรายการ');
  await timeline.scrollIntoViewIfNeeded();
  await capture(page, { path: 'test-results/activity-history-mobile.png', fullPage: false });
});

test('PDF report exports every concise event even when the timeline is filtered', async ({ page, context }) => {
  // Exercise the actual report popup offline; native print is used when the CDN is unavailable.
  await context.route('**/html2pdf.bundle.min.js', r => r.fulfill({ contentType: 'application/javascript', body: '' }));
  await context.route('https://fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
  await context.addInitScript(() => { window.print = () => {}; });
  const login = await page.request.post('/api/login', { data: { idOrEmail: 'qa-admin', pin: 'qa-only-876543' } });
  const { token } = await login.json(); const headers = { Authorization: `Bearer ${token}` };
  const id = 'qa-report-' + Date.now();
  expect((await page.request.post('/api/suppliers', { headers, data: { id, name: 'รายงานประวัติเต็ม', category: 'ชา', rating: 4, quickTags: [], photos: { storefrontAndAtmosphere: [], contactCards: [] }, catalogItems: [], location: { lat: 13.7, lng: 100.5 }, status: 'scouted' } })).ok()).toBeTruthy();
  const longNote = 'ข้อความส่งต่องานที่ต้องเก็บไว้ครบทุกบรรทัด\n'.repeat(40) + 'จบรายละเอียดส่งต่อ';
  expect((await page.request.post(`/api/suppliers/${id}/actions`, { headers, data: { action: 'handoff', operationId: id+'-handoff', revision: 1, data: { handoffStage: 'sample_test', assignedTo: 'qa-reviewer', handoffNotes: longNote } } })).ok()).toBeTruthy();
  expect((await page.request.post(`/api/suppliers/${id}/actions`, { headers, data: { action: 'comment', operationId: id+'-comment', data: { text: 'คำตอบในประวัติรายงาน' } } })).ok()).toBeTruthy();
  await page.addInitScript(t => sessionStorage.setItem('vitcha_session_token', t), token);
  await page.goto(`/?view=${id}&type=supplier`, { waitUntil: 'domcontentloaded' });
  const timeline = page.getByTestId('activity-timeline'); await expect(timeline).toBeVisible();
  await timeline.getByLabel('ประเภทประวัติ').selectOption('comments');
  await expect(timeline.getByTestId('activity-event')).toHaveCount(1);
  const popupPromise = page.waitForEvent('popup');
  await page.getByRole('button', { name: 'ดาวน์โหลด PDF', exact: true }).click();
  const popup = await popupPromise;
  const history = popup.locator('#activity-history');
  await expect(history.locator('.audit-event')).toHaveCount(3);
  await expect(history).toContainText('อัปเดตการส่งต่องาน');
  await expect(history).toContainText('แสดงความคิดเห็น');
  await expect(history).not.toContainText('จบรายละเอียดส่งต่อ');
  await expect(history).not.toContainText('คำตอบในประวัติรายงาน');
  await expect(history.locator('img.person-avatar')).toHaveCount(3);
  await expect(history.locator('img.person-avatar').first()).toHaveAttribute('alt', 'โปรไฟล์ QA admin');
  await expect(history.locator('img:not(.person-avatar), audio, video, .audit-change, .audit-stage')).toHaveCount(0);
  await expect(popup.locator('#record-comments img.person-avatar')).toHaveCount(1);
  expect(await history.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBeTruthy();
  await popup.emulateMedia({ media: 'print' });
  const pdf = await popup.pdf({ format: 'A4', printBackground: true });
  expect(pdf.subarray(0, 5).toString()).toBe('%PDF-');
  expect(pdf.length).toBeGreaterThan(5000);
  await popup.close();
});
