import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { build } from 'esbuild';
import { createApp } from '../server/app.js';
import { DEFAULT_DATABASE } from '../server/defaults.js';
const result = await build({ entryPoints: ['src/utils/seedData.ts'], bundle: true, write: false, format: 'esm', platform: 'node' });
const compiled = result.outputFiles[0].text;
const seed = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const defaults = structuredClone(DEFAULT_DATABASE);
defaults.users = defaults.users.map(u => ({ ...u, pin: 'qa-only-876543' }));
for (const role of ['admin', 'reviewer', 'viewer']) defaults.users.push({ id: `qa-${role}`, emailOrId: `qa-${role}`, name: `QA ${role}`, alias: `QA ${role}`, role, pin: 'qa-only-876543', avatar: '', createdAt: new Date().toISOString() });
defaults.suppliers = seed.INITIAL_SUPPLIERS;
defaults.drinkStores = seed.INITIAL_DRINK_STORES;
defaults.invites.push({ id: 'qa-invite', code: 'QA-INVITE', role: 'reviewer', isUsed: false });
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vitcha-browser-qa-'));
const server = createApp({ dataDir: dir, defaults }).listen(3901, '127.0.0.1');
const close = () => server.close(() => { fs.rmSync(dir, { recursive: true, force: true }); process.exit(0); });
process.on('SIGTERM', close); process.on('SIGINT', close);
